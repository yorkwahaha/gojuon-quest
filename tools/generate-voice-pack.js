'use strict';
// Explicit maintenance command for the recorded pack and optional media.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { spawnSync } = require('node:child_process');
const { model, styleFor, hash, fingerprint, validateAudio, atomicWrite } = require('./voice-pack.cjs');
const ROOT = path.resolve(__dirname, '..');
const args = process.argv.slice(2);
const option = key => (args.find(a => a.startsWith(key + '=')) || '').slice(key.length + 1);
const only = option('--only');
const ids = new Set(option('--ids').split(',').filter(Boolean));
const force = args.includes('--force');
const syncOnly = args.includes('--sync-only');
const metadataFile = path.join(__dirname, 'voice-pack-metadata.json');
const metadata = fs.existsSync(metadataFile) ? JSON.parse(fs.readFileSync(metadataFile, 'utf8')) : {};
const QUESTIONS = vm.runInNewContext(fs.readFileSync(path.join(ROOT,'js/data.js'),'utf8') + '\nQUESTIONS');
if (only && !['jojo', 'jjk'].includes(only)) throw Error('--only must be jojo or jjk');
for (const id of ids) if (!QUESTIONS.some(q => q.id === id)) throw Error('Unknown question id: ' + id);
async function main() {
  const manifest = {}, allowed = [];
  const seen = new Set();
  let failed = 0, generated = 0;
  for (const q of QUESTIONS) {
    if (seen.has(q.kana)) continue;
    seen.add(q.kana);
    const target = path.join(ROOT,'assets/voice',q.id+'.mp3');
    const selected = (!only || only === q.anime) && (!ids.size || ids.has(q.id));
    let valid = false;
    try { validateAudio(fs.readFileSync(target)); valid = metadata[q.id]?.fingerprint === fingerprint(q); } catch (_) {}
    if (!syncOnly && selected && (force || !valid)) {
      try {
        if (!process.env.FISH_API_KEY) throw Error('FISH_API_KEY is missing');
        const style = styleFor(q);
        const res = await fetch('https://api.fish.audio/v1/tts', {
          method:'POST', signal:AbortSignal.timeout(45000),
          headers:{Authorization:'Bearer '+process.env.FISH_API_KEY,'Content-Type':'application/json',model},
          body:JSON.stringify({text:style.prefix+q.kana,reference_id:style.id,format:'mp3',language:'ja',normalize:true,prosody:style.prosody}),
        });
        if (!res.ok) throw Error('Voice provider HTTP '+res.status);
        if (!/^audio\//i.test(res.headers.get('content-type') || '')) throw Error('Non-audio response');
        const buf = Buffer.from(await res.arrayBuffer());
        validateAudio(buf);
        const check = spawnSync('ffmpeg',['-v','error','-i','pipe:0','-f','null','-'],{input:buf,timeout:15000,windowsHide:true});
        if (check.error || check.status !== 0) throw Error('Audio decode validation failed');
        atomicWrite(target,buf);
        metadata[q.id]={kana:q.kana,fingerprint:fingerprint(q)};
        atomicWrite(metadataFile,JSON.stringify(metadata,null,2)+'\n');
        valid=true; generated++;
        console.log('generated',q.id,q.kana,buf.length);
      } catch (error) { console.error('failed',q.id,error.message); failed++; }
    }
    if (valid) {
      const rel='assets/voice/'+q.id+'.mp3?v='+hash(fs.readFileSync(target)).slice(0,12);
      manifest[q.kana]=rel;
    } else { console.error('stale or unavailable',q.id); if (!selected || syncOnly) failed++; }
  }
  const allowedKeys = new Set();
  for (const q of QUESTIONS) {
    const key = q.anime + '\n' + q.kana;
    if (manifest[q.kana] && !allowedKeys.has(key)) {
      allowedKeys.add(key);
      allowed.push({anime:q.anime,kana:q.kana,type:q.type,...(q.voiceSide ? {voiceSide:q.voiceSide} : {}),file:manifest[q.kana]});
    }
  }
  // Publish both mappings together only when the entire pack is valid.
  if (!failed && Object.keys(manifest).length === seen.size) {
    const media = ['assets/bgm', 'assets/sfx'].flatMap(dir => fs.readdirSync(path.join(ROOT, dir), { withFileTypes: true })
      .filter(file => file.isFile() && /^[a-z]+\.mp3$/.test(file.name))
      .map(file => dir + '/' + file.name)).sort();
    atomicWrite(path.join(ROOT,'js/voice-manifest.js'),"'use strict';\n// Generated by tools/generate-voice-pack.js\nconst VOICE_PACK = "+JSON.stringify(manifest,null,1)+';\n'
      + 'const OPTIONAL_MEDIA = new Set('+JSON.stringify(media)+');\n');
    atomicWrite(path.join(ROOT,'worker/allowlist.json'),JSON.stringify(allowed,null,2)+'\n');
  }
  console.log(JSON.stringify({generated,failed,readings:seen.size,ready:Object.keys(manifest).length}));
  if(failed)process.exitCode=1;
}
main().catch(error=>{console.error(error.message);process.exitCode=1;});
